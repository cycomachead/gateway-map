#!/usr/bin/env python3
"""Build src/data/gateway/occupants.ts from the EECS faculty directory.

    python3 tools/faculty/import_faculty.py [faculty.html | URL] [output.ts]
    npm run occupants          # same thing with the defaults below

Reads https://www2.eecs.berkeley.edu/Faculty/Lists/faculty.html (or a saved copy of it),
keeps every faculty member whose office is in Gateway, and writes the room-number → names
map the map site reads. Only the standard library is used.

Each person on the directory page is one entry: an <h3> holding a link to their homepage
under /Faculty/Homepages/, then a paragraph whose first line is the office and contact
details ("4193 Gateway Building, 510-642-7034; pabbeel@cs.berkeley.edu"). Office hours
later in the entry mention Gateway classrooms, so only that contact line is searched for a
room; it may read "4193 Gateway Building", "Gateway Building 4193", "Gateway 4193" or
"Gateway Building, Room 4193". People with no Gateway office are skipped.
"""
from __future__ import annotations

import html
import re
import sys
import urllib.request
from collections import defaultdict

SOURCE_URL = 'https://www2.eecs.berkeley.edu/Faculty/Lists/faculty.html'
DEFAULT_OUT = 'src/data/gateway/occupants.ts'

ROOM = r'([A-Z]?\d{3,4}[A-Z]?)'
OFFICE_PATTERNS = [
    re.compile(r'\b' + ROOM + r'\s+Gateway\b', re.I),
    re.compile(r'\bGateway(?:\s+Building)?(?:\s*,)?\s*(?:Room|Rm\.?|#)?\s*' + ROOM + r'\b', re.I),
]

# One directory entry: the name link in its heading, then the paragraph of details.
ENTRY = re.compile(
    r'<h3>.*?<a\s+href="[^"]*/Faculty/Homepages/[^"]*"[^>]*>(?P<name>[^<]+)</a>.*?</h3>\s*<p>(?P<body>.*?)</p>',
    re.S | re.I,
)
# The contact line: after the title (the first <strong>…</strong>), up to the next labelled line.
CONTACT = re.compile(r'(?:<strong>.*?</strong>)?\s*(?:<br\s*/?>)?\s*(?P<line>.*?)(?=<br\s*/?>\s*<strong>|$)', re.S | re.I)


def text(fragment: str) -> str:
    return re.sub(r'\s+', ' ', html.unescape(re.sub(r'<[^>]+>', ' ', fragment))).strip()


def tidy_name(name: str) -> str:
    """The directory shows "First Last"; turn a "Last, First" entry around if one appears."""
    if ',' in name:
        last, first = (part.strip() for part in name.split(',', 1))
        if first and last:
            return f'{first} {last}'
    return name


def gateway_room(contact_line: str) -> str | None:
    for pattern in OFFICE_PATTERNS:
        m = pattern.search(contact_line)
        if m:
            return m.group(1).upper()
    return None


def read(source: str) -> str:
    if re.match(r'https?://', source):
        req = urllib.request.Request(source, headers={'User-Agent': 'gateway-map occupants importer'})
        with urllib.request.urlopen(req, timeout=30) as resp:
            return resp.read().decode(resp.headers.get_content_charset() or 'utf-8', 'replace')
    with open(source, encoding='utf-8', errors='replace') as f:
        return f.read()


def parse(page: str) -> dict[str, list[str]]:
    rooms: dict[str, list[str]] = defaultdict(list)
    entries = 0
    for entry in ENTRY.finditer(page):
        entries += 1
        name = tidy_name(text(entry.group('name')))
        contact = CONTACT.match(entry.group('body'))
        room = gateway_room(text(contact.group('line'))) if contact else None
        if room and name and name not in rooms[room]:
            rooms[room].append(name)
    if not entries:
        sys.exit('No faculty entries found; has the directory page changed its layout?')
    print(f'{entries} faculty on the page', file=sys.stderr)
    return dict(sorted(rooms.items()))


def ts_string(s: str) -> str:
    return "'" + s.replace('\\', '\\\\').replace("'", "\\'") + "'"


def emit(rooms: dict[str, list[str]]) -> str:
    lines = [
        '// GENERATED by tools/faculty/import_faculty.py (`npm run occupants`) — edit by hand only to add',
        '// people who are not on the directory page; the next import overwrites the file.',
        '/**',
        ' * Who sits where: plan room number → the people whose office it is.',
        ' *',
        f' * Source: the EECS faculty directory, {SOURCE_URL}',
        ' * (only faculty who list a Gateway office there). Keys are the room numbers printed on the',
        " * plans (`'4123'`), values are display names. A room with several occupants lists them all;",
        ' * rooms that match no space on any floor are reported in the browser console on start.',
        ' */',
    ]
    if not rooms:
        lines.append('export const OCCUPANTS: Record<string, string[]> = {};')
    else:
        lines.append('export const OCCUPANTS: Record<string, string[]> = {')
        for room, names in rooms.items():
            lines.append(f"  {ts_string(room)}: [{', '.join(ts_string(n) for n in names)}],")
        lines.append('};')
    return '\n'.join(lines) + '\n'


def main(argv: list[str]) -> None:
    if len(argv) > 1 and argv[1] in ('-h', '--help'):
        sys.exit(__doc__)
    source = argv[1] if len(argv) > 1 else SOURCE_URL
    out = argv[2] if len(argv) > 2 else DEFAULT_OUT
    rooms = parse(read(source))
    with open(out, 'w', encoding='utf-8') as f:
        f.write(emit(rooms))
    people = sum(len(n) for n in rooms.values())
    print(f'{people} faculty in {len(rooms)} Gateway rooms → {out}')


if __name__ == '__main__':
    main(sys.argv)
